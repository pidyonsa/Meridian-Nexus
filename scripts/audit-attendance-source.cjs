"use strict";

const h = require("../tmp/sharepoint_helpers");
const ExcelJS = require("../functions/node_modules/exceljs");
const fs = require("node:fs");
const vm = require("node:vm");

async function main() {
  const token = await h.graphToken();
  const url = "https://meridiangroupza.sharepoint.com/:f:/s/PowerBI9-PowerBI-PG/IgAB-vX5oVK_TbcKndllxkM9AWd6oGM0ZWE43c12RKpHWAQ?e=lb3Euy";
  const folder = await h.graphJson(token, `/shares/${h.shareId(url)}/driveItem?$select=id,name,folder,parentReference,webUrl`);
  if (!folder.folder || !folder.parentReference?.driveId) throw new Error("The link must resolve to a SharePoint folder.");
  console.log(JSON.stringify({ folder }, null, 2));
  async function list(id, depth = 0) {
    let next = `/drives/${folder.parentReference.driveId}/items/${id}/children?$select=id,name,folder,file,size,lastModifiedDateTime&$top=200`;
    const seen = new Set();
    while (next) {
      if (seen.has(next) || seen.size >= 100) throw new Error("Incomplete SharePoint listing.");
      seen.add(next);
      const page = await h.graphJson(token, next);
      for (const item of page.value || []) {
        console.log(JSON.stringify({ depth, name: item.name, folder: !!item.folder, size: item.size, modified: item.lastModifiedDateTime }));
        if (process.argv.includes("--workbook") && item.file && /\.xlsx$/i.test(item.name) && item.size <= 25 * 1024 * 1024) {
          const response = await fetch(`https://graph.microsoft.com/v1.0/drives/${folder.parentReference.driveId}/items/${item.id}/content`, { headers: { Authorization: `Bearer ${token}` } });
          if (!response.ok) throw new Error(`Report read failed: ${response.status}`);
          const workbook = new ExcelJS.Workbook();
          await workbook.xlsx.load(Buffer.from(await response.arrayBuffer()));
          const backend = fs.readFileSync(require.resolve("../functions/index.js"), "utf8");
          const context = vm.createContext({ Date });
          for (const name of ["attendanceCellValue", "attendanceText", "attendanceHeader", "attendanceHeaderColumn", "attendanceWorksheetHeader", "attendanceWorksheet", "salesforceDateValue", "attendanceDateValue"]) {
            const fn = backend.match(new RegExp(`(?:async )?function ${name}\\([^]*?\\r?\\n\\}`));
            vm.runInContext(fn[0], context);
          }
          for (const sheet of workbook.worksheets) {
            const headers = [];
            for (let r = 1; r <= Math.min(30, sheet.rowCount); r++) {
              if (sheet.getRow(r).values.some(v => String(v).replace(/[^a-z]/gi, "").toLowerCase() === "visitdate")) headers.push({ row: r, columns: sheet.getRow(r).values });
            }
            console.log(JSON.stringify({ worksheet: sheet.name, rows: sheet.rowCount, headers }));
            if (headers[0]) {
              const metadata = [];
              for (let r = 1; r < headers[0].row; r++) metadata.push({ row: r, cells: sheet.getRow(r).values.map(value => typeof value === "string" ? value.replace(/Generated by [^]*$/i, "Generated by [redacted]") : value) });
              console.log(JSON.stringify({ reportMetadata: metadata }));
            }
          }
          const contract = context.attendanceWorksheet(workbook, { storeCode: ["storecode"], employeeId: ["employeeid"], visitDate: ["visitdate"], checkIn: ["checkinlocationcompliance"], checkOut: ["checkoutlocationcompliance"] }, "SharePoint source");
          const counts = {};
          for (let r = contract.rowNumber + 1; r <= contract.worksheet.rowCount; r++) {
            const date = context.attendanceDateValue(contract.worksheet.getRow(r).getCell(contract.columns.visitDate).value);
            if (date) counts[date] = (counts[date] || 0) + 1;
          }
          console.log(JSON.stringify({ visitDates: Object.fromEntries(Object.entries(counts).sort(([a], [b]) => a.localeCompare(b))) }));
        }
        if (depth < 1 && item.folder) await list(item.id, depth + 1);
      }
      const nextLink = page["@odata.nextLink"];
      if (nextLink && !nextLink.startsWith("https://graph.microsoft.com/v1.0/")) throw new Error("Unexpected paging destination.");
      next = nextLink ? nextLink.slice("https://graph.microsoft.com/v1.0".length) : "";
    }
  }
  await list(folder.id);
}

main().catch(error => { console.error(error.message); process.exitCode = 1; });
