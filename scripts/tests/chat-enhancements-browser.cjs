const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const puppeteer = require("../../functions/node_modules/puppeteer-core");
const { createServer } = require("../chat-preview.cjs");
const output = path.resolve(__dirname, "../../.tmp/chat-enhancements-verification");
fs.mkdirSync(output, { recursive: true });
(async () => {
  const server = createServer(); await new Promise(resolve => server.listen(0, "127.0.0.1", resolve));
  const url = `http://127.0.0.1:${server.address().port}/?enhanced`;
  let browser;
  try {
    browser = await puppeteer.launch({ executablePath: "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe", headless: true, args: ["--no-first-run", "--disable-extensions", "--use-fake-ui-for-media-stream", "--use-fake-device-for-media-stream"] });
    const page = await browser.newPage(), errors = [];
    page.setDefaultTimeout(20000); page.on("pageerror", error => errors.push(error.message));
    await page.setRequestInterception(true); page.on("request", request => new URL(request.url()).hostname === "127.0.0.1" || request.url().startsWith("blob:") ? request.continue() : request.abort());
    await page.setViewport({ width: 1440, height: 900 });
    await page.goto(url, { waitUntil: "networkidle0" }); await page.waitForSelector('[data-room="field"]');
    await page.click('[data-room="field"]'); await page.waitForSelector('[data-action="attach"]');
    console.log("Offline queue survives reload; reconnect sends once...");
    await page.evaluate(() => { window.isOffline = true; Object.defineProperty(navigator, "onLine", { get: () => !window.isOffline, configurable: true }); dispatchEvent(new Event("offline")); });
    await page.type('.mc-compose textarea', "Offline shelf check"); await page.click('.mc-compose [type=submit]');
    await page.waitForFunction(() => document.querySelector('.mc-outbox').textContent.includes("Queued / offline"));
    assert.equal(await page.evaluate(() => chatTest.calls.filter(c => c.action === "send").length), 0);
    assert.equal(await page.evaluate(async () => (await MeridianChatTools.list("admin")).length), 1);
    await page.reload({ waitUntil: "networkidle0" }); await page.waitForSelector('[data-room="field"]'); await page.click('[data-room="field"]');
    await page.waitForFunction(() => chatTest.messages.field.some(row => row.text === "Offline shelf check"));
    await page.waitForFunction(async () => (await MeridianChatTools.list("admin")).length === 0);
    assert.equal(await page.evaluate(() => chatTest.messages.field.filter(row => row.text === "Offline shelf check").length), 1);
    console.log("Retry after a lost send response is idempotent...");
    await page.evaluate(() => { chatTest.failSendAfterSave = true; });
    await page.type('.mc-compose textarea', "Lost response check"); await page.click('.mc-compose [type=submit]');
    await page.waitForFunction(async () => (await MeridianChatTools.list("admin")).some(row => row.error.includes("after send")));
    await page.waitForSelector('[data-action="queue-retry"]'); await page.click('[data-action="queue-retry"]');
    await page.waitForFunction(async () => (await MeridianChatTools.list("admin")).length === 0);
    assert.equal(await page.evaluate(() => chatTest.messages.field.filter(row => row.text === "Lost response check").length), 1);
    console.log("Attachments, validation and private preview...");
    await page.evaluate(() => {
      const input = document.querySelector('[name=attachments]'), transfer = new DataTransfer();
      transfer.items.add(new File(["Product,Count\nExample,10"], "Store-check.csv", { type: "text/csv" })); input.files = transfer.files; input.dispatchEvent(new Event("change", { bubbles: true }));
    });
    await page.waitForFunction(() => document.querySelector('.mc-attachments').textContent.includes("Store-check.csv"));
    await page.click('.mc-compose [type=submit]'); await page.waitForSelector('.mc-attachment');
    await page.click('.mc-attachment'); await page.waitForSelector('.mc-media-dialog[open]');
    assert.ok(await page.$eval('.mc-media-preview a', node => node.href.startsWith("blob:")));
    await page.click('[data-action=media-close]');
    console.log("Voice recording, preview and upload...");
    await page.click('[data-action=voice]'); await page.waitForSelector('[data-action=voice-stop]');
    await page.waitForFunction(() => document.querySelector('.mc-recording')?.textContent.includes("Recording 2"));
    await page.click('[data-action=voice-stop]'); await page.waitForSelector('[data-action=voice-preview]');
    await page.click('[data-action=voice-preview]'); await page.waitForSelector('.mc-media-dialog[open] audio');
    assert.equal(await page.$eval('audio', node => node.controls), true);
    await page.click('[data-action=media-close]'); await page.click('.mc-compose [type=submit]');
    await page.waitForFunction(() => chatTest.messages.field.some(row => row.attachments?.some(file => file.kind === "voice")));
    await page.screenshot({ path: path.join(output, "desktop.png"), fullPage: true });
    console.log("AI memory, reviewed task drafting and reminders...");
    await page.click('[data-action=assistant]'); await page.type('.mc-ai-compose textarea', "Which visits need attention?"); await page.click('.mc-ai-compose [type=submit]');
    await page.waitForSelector('.mc-ai-turn:not(.own)');
    await page.type('.mc-ai-compose textarea', "What about the previous month?"); await page.click('.mc-ai-compose [type=submit]');
    await page.waitForFunction(() => document.querySelectorAll('.mc-ai-turn:not(.own)').length === 2);
    const options = await page.evaluate(() => chatTest.aiOptions);
    assert.equal(options[0].conversationId, options[1].conversationId); assert.notEqual(options[0].requestId, options[1].requestId);
    await page.click('[data-action=assistant-task]'); await page.waitForSelector('.mc-task-dialog[open]');
    assert.equal(await page.evaluate(() => chatTest.tasks.length), 0);
    await page.$eval('.mc-task-form [name=title]', node => { node.value = "Reviewed field task"; });
    await page.$eval('.mc-task-form [name=remindAt]', node => { node.value = "2026-09-10T08:00"; });
    await page.screenshot({ path: path.join(output, "reviewed-task.png"), fullPage: true });
    await page.click('.mc-task-form [type=submit]'); await page.waitForFunction(() => chatTest.tasks.length === 1);
    const task = await page.evaluate(() => chatTest.calls.find(call => call.action === "taskCreateReviewed"));
    assert.equal(task.confirmed, true); assert.equal(task.remindAt, "2026-09-10T06:00:00.000Z"); assert.equal(task.title, "Reviewed field task");
    await page.click('[data-action=notifications]'); await page.waitForSelector('.mc-notification-dialog[open]');
    assert.ok((await page.$eval('.mc-notification-state', node => node.textContent)).includes("Not configured"));
    await page.click('[data-action=notifications-close]');
    console.log("Mobile layout and account isolation...");
    for (const width of [390, 320]) {
      await page.setViewport({ width, height: 844 });
      await page.click('[data-action=back]'); await page.click('[data-room=field]');
      await page.screenshot({ path: path.join(output, `mobile-${width}.png`), fullPage: true });
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true, `overflow at ${width}`);
      assert.equal(await page.$eval('.mc-compose', node => node.getBoundingClientRect().right <= innerWidth + 1), true);
    }
    await page.evaluate(async () => {
      window.isOffline = true; Object.defineProperty(navigator, "onLine", { get: () => false, configurable: true });
      await MeridianChatTools.add("admin", { action: "send", roomId: "field", requestId: crypto.randomUUID(), text: "Private queued text" }, []);
      chatTest.session.stop(); await MeridianChatTools.identity("rep");
    });
    assert.equal(await page.evaluate(async () => (await MeridianChatTools.list("admin")).length), 0);
    assert.equal(await page.evaluate(() => document.body.textContent.includes("Private queued text")), false);
    assert.deepEqual(errors, []);
    console.log("PASS: offline persistence, idempotency, attachments, voice, AI memory, reviewed tasks, reminders, notifications state, mobile and account isolation.");
  } finally { await browser?.close(); await new Promise(resolve => server.close(resolve)); }
})().catch(error => { console.error(error); process.exitCode = 1; });
